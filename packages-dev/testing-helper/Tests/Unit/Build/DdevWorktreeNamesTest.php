<?php

declare(strict_types=1);

namespace FGTCLB\TestingHelper\Tests\Unit\Build;

use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\TestCase;

/**
 * "Build/Scripts/ddevWorktreeNames.sh" and the "Build/git-hooks/post-checkout"
 * hook that runs it: the DDEV instances of a linked worktree get project names
 * of their own, the main checkout keeps the committed ones.
 *
 * Each test builds a throwaway repository holding copies of the script, the
 * hook and two instance configurations - the script derives the checkout it
 * works on from its own location. Git runs isolated from any global or system
 * configuration, so a hooks path or identity of the machine cannot leak in.
 */
final class DdevWorktreeNamesTest extends TestCase
{
    private const MARKER = '# Generated by Build/Scripts/ddevWorktreeNames.sh - rewritten on every run, do not edit.';

    private string $directory;

    protected function setUp(): void
    {
        parent::setUp();
        $this->directory = sys_get_temp_dir() . '/ddev-worktree-names-' . bin2hex(random_bytes(4));
        mkdir($this->directory);
        // Physical path: the script hashes the resolved one.
        $this->directory = (string)realpath($this->directory);

        $repository = dirname(__DIR__, 5);
        $main = $this->directory . '/main';
        mkdir($main . '/Build/Scripts', 0777, true);
        mkdir($main . '/Build/git-hooks', 0777, true);
        copy($repository . '/Build/Scripts/ddevWorktreeNames.sh', $main . '/Build/Scripts/ddevWorktreeNames.sh');
        copy($repository . '/Build/git-hooks/post-checkout', $main . '/Build/git-hooks/post-checkout');
        chmod($main . '/Build/Scripts/ddevWorktreeNames.sh', 0755);
        chmod($main . '/Build/git-hooks/post-checkout', 0755);
        foreach (['core-12' => 'core12-academics-v2', 'core-13' => 'core13-academics-v2'] as $instance => $name) {
            mkdir($main . '/' . $instance . '/.ddev', 0777, true);
            file_put_contents($main . '/' . $instance . '/.ddev/config.yaml', "name: {$name}\ntype: typo3\n");
        }
        file_put_contents($main . '/.gitignore', "config.worktree.local.yaml\n");
        $this->git($main, 'init', '-q', '-b', 'main');
        $this->git($main, 'add', '-A');
        $this->git($main, 'commit', '-q', '-m', 'Initial');
    }

    protected function tearDown(): void
    {
        exec('rm -rf ' . escapeshellarg($this->directory));
        parent::tearDown();
    }

    #[Test]
    public function mainCheckoutKeepsTheCommittedNames(): void
    {
        [$status, $output] = $this->execute($this->directory . '/main/Build/Scripts/ddevWorktreeNames.sh');

        $this->assertSame(0, $status, $output);
        $this->assertStringContainsString('Main checkout', $output);
        $this->assertFileDoesNotExist($this->directory . '/main/core-12/.ddev/config.worktree.local.yaml');
        $this->assertFileDoesNotExist($this->directory . '/main/core-13/.ddev/config.worktree.local.yaml');
    }

    #[Test]
    public function linkedWorktreeGetsNamesDerivedFromItsPath(): void
    {
        $worktree = $this->addWorktree('feature', hooks: false);

        [$status, $output] = $this->execute($worktree . '/Build/Scripts/ddevWorktreeNames.sh');

        $this->assertSame(0, $status, $output);
        $suffix = $this->suffix($worktree);
        $this->assertSame('core12-academics-v2-' . $suffix, $this->writtenName($worktree . '/core-12'));
        $this->assertSame('core13-academics-v2-' . $suffix, $this->writtenName($worktree . '/core-13'));
    }

    #[Test]
    public function twoWorktreesGetDifferentNames(): void
    {
        $first = $this->addWorktree('first', hooks: false);
        $second = $this->addWorktree('second', hooks: false);

        $this->execute($first . '/Build/Scripts/ddevWorktreeNames.sh');
        $this->execute($second . '/Build/Scripts/ddevWorktreeNames.sh');

        $this->assertNotSame($this->writtenName($first . '/core-12'), $this->writtenName($second . '/core-12'));
    }

    #[Test]
    public function secondRunLeavesTheFileUnchanged(): void
    {
        $worktree = $this->addWorktree('feature', hooks: false);
        $this->execute($worktree . '/Build/Scripts/ddevWorktreeNames.sh');
        $before = file_get_contents($worktree . '/core-12/.ddev/config.worktree.local.yaml');

        [$status, $output] = $this->execute($worktree . '/Build/Scripts/ddevWorktreeNames.sh');

        $this->assertSame(0, $status, $output);
        $this->assertStringContainsString('(unchanged)', $output);
        $this->assertSame($before, file_get_contents($worktree . '/core-12/.ddev/config.worktree.local.yaml'));
    }

    #[Test]
    public function fileNotWrittenByTheScriptIsLeftAlone(): void
    {
        $worktree = $this->addWorktree('feature', hooks: false);
        file_put_contents($worktree . '/core-12/.ddev/config.worktree.local.yaml', "name: chosen-by-hand\n");

        [$status, $output] = $this->execute($worktree . '/Build/Scripts/ddevWorktreeNames.sh');

        $this->assertSame(0, $status, $output);
        $this->assertStringContainsString('core-12/.ddev/config.worktree.local.yaml was not written by this script', $output);
        $this->assertSame("name: chosen-by-hand\n", file_get_contents($worktree . '/core-12/.ddev/config.worktree.local.yaml'));
        $this->assertSame('core13-academics-v2-' . $this->suffix($worktree), $this->writtenName($worktree . '/core-13'));
    }

    #[Test]
    public function hookNamesTheInstancesOnWorktreeAdd(): void
    {
        $this->git($this->directory . '/main', 'config', 'core.hooksPath', 'Build/git-hooks');

        $worktree = $this->addWorktree('feature', hooks: true);

        $this->assertSame('core12-academics-v2-' . $this->suffix($worktree), $this->writtenName($worktree . '/core-12'));
        $this->assertSame('core13-academics-v2-' . $this->suffix($worktree), $this->writtenName($worktree . '/core-13'));
        $this->assertFileDoesNotExist($this->directory . '/main/core-12/.ddev/config.worktree.local.yaml');
    }

    private function addWorktree(string $name, bool $hooks): string
    {
        $path = $this->directory . '/' . $name;
        $arguments = $hooks ? [] : ['-c', 'core.hooksPath=/dev/null'];
        $this->git($this->directory . '/main', ...[...$arguments, 'worktree', 'add', '-q', '-b', $name, $path]);
        return $path;
    }

    /**
     * What "git hash-object --stdin" prints for the path, computed without git.
     */
    private function suffix(string $worktree): string
    {
        return substr(sha1('blob ' . strlen($worktree) . "\0" . $worktree), 0, 8);
    }

    private function writtenName(string $instance): string
    {
        $content = (string)file_get_contents($instance . '/.ddev/config.worktree.local.yaml');
        $this->assertStringStartsWith(self::MARKER . "\n", $content);
        $this->assertSame(1, preg_match('/^name: (\S+)$/m', $content, $matches), $content);
        return $matches[1];
    }

    private function git(string $directory, string ...$arguments): void
    {
        [$status, $output] = $this->execute('git', '-C', $directory, '-c', 'user.name=Test', '-c', 'user.email=test@example.com', ...$arguments);
        $this->assertSame(0, $status, $output);
    }

    /**
     * @return array{int, string}
     */
    private function execute(string ...$arguments): array
    {
        $environment = 'GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1';
        $output = [];
        $status = 0;
        exec($environment . ' ' . implode(' ', array_map('escapeshellarg', $arguments)) . ' 2>&1', $output, $status);
        return [$status, implode("\n", $output)];
    }
}
