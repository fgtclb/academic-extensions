#!/usr/bin/env bash

# ----------------------------------------------------------------------------------------------------------------------
# Gives the DDEV instances of a linked git worktree project names of their own.
#
# Every checkout carries the same "core-*/.ddev/config.yaml", and with it the same DDEV project names. DDEV refuses a
# name that is registered for another directory - whether that project runs or is only stopped - so a second checkout
# of the same version line cannot start its instances without "ddev stop --unlist" in the first one.
#
# In a linked worktree this script writes "core-*/.ddev/config.worktree.local.yaml" with the committed name as prefix
# and a hash of the worktree's absolute path as suffix, for example "core13-academics-v3-1a2b3c4d". DDEV merges every
# ".ddev/config.*.yaml" over "config.yaml", in lexical order, so the file overrides the committed name - and a
# "config.local.yaml" of your own, which it sorts after. Both instances of one worktree share the suffix.
#
# The main checkout is left alone: it keeps the committed names. A file this script did not write is never touched.
#
# Run by "Build/git-hooks/post-checkout" on "git worktree add" and on every branch checkout inside a worktree, once
# "git config core.hooksPath Build/git-hooks" is set. Run it by hand in a worktree created without the hook.
# See "docs/development/instances.md", section "Instances in git worktrees".
# ----------------------------------------------------------------------------------------------------------------------
set -euo pipefail

MARKER="# Generated by Build/Scripts/ddevWorktreeNames.sh - rewritten on every run, do not edit."
QUIET=0

usage() {
    cat <<EOF
Usage: Build/Scripts/ddevWorktreeNames.sh [-q] [-h]

Writes "core-*/.ddev/config.worktree.local.yaml" with a DDEV project name unique
to this linked git worktree. Does nothing in the main checkout.

Options:
    -q  Report only warnings, not what was written or left unchanged.
    -h  Show this help.
EOF
}

info() {
    if [[ ${QUIET} -eq 0 ]]; then
        echo "$*"
    fi
}

while getopts "qh" OPT; do
    case ${OPT} in
        q)
            QUIET=1
            ;;
        h)
            usage
            exit 0
            ;;
        *)
            usage >&2
            exit 1
            ;;
    esac
done

# The checkout this script belongs to, not the current directory: the hook runs it from the new worktree, a manual run
# may start anywhere. "pwd -P" resolves symbolic links, so one directory always yields one hash.
CHECKOUT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"

GIT_DIR_ABSOLUTE="$(git -C "${CHECKOUT}" rev-parse --path-format=absolute --git-dir)"
GIT_COMMON_DIR_ABSOLUTE="$(git -C "${CHECKOUT}" rev-parse --path-format=absolute --git-common-dir)"
if [[ "${GIT_DIR_ABSOLUTE}" == "${GIT_COMMON_DIR_ABSOLUTE}" ]]; then
    info "Main checkout: the DDEV instances keep their committed project names."
    exit 0
fi

# "git hash-object" instead of "sha256sum" or "shasum": git is there wherever this runs, the other two are not.
SUFFIX="$(printf '%s' "${CHECKOUT}" | git hash-object --stdin | cut -c1-8)"

shopt -s nullglob
for CONFIG in "${CHECKOUT}"/core-*/.ddev/config.yaml; do
    INSTANCE="$(basename "$(dirname "$(dirname "${CONFIG}")")")"
    TARGET="$(dirname "${CONFIG}")/config.worktree.local.yaml"

    COMMITTED_NAME="$(sed -n -E 's/^name:[[:space:]]*["'\'']?([A-Za-z0-9-]+)["'\'']?[[:space:]]*$/\1/p' "${CONFIG}" | head -n 1)"
    if [[ -z "${COMMITTED_NAME}" ]]; then
        echo "Warning: ${INSTANCE}/.ddev/config.yaml names no project, skipped." >&2
        continue
    fi

    if [[ -f "${TARGET}" ]] && [[ "$(head -n 1 "${TARGET}")" != "${MARKER}" ]]; then
        echo "Warning: ${INSTANCE}/.ddev/config.worktree.local.yaml was not written by this script, left alone." >&2
        continue
    fi

    NAME="${COMMITTED_NAME}-${SUFFIX}"
    CONTENT="${MARKER}
# The committed name \"${COMMITTED_NAME}\" belongs to the main checkout. This worktree
# uses its own, derived from its path - see docs/development/instances.md:
# ${CHECKOUT}
name: ${NAME}"

    if [[ -f "${TARGET}" ]] && [[ "$(cat "${TARGET}")" == "${CONTENT}" ]]; then
        info "${INSTANCE}: ${NAME} (unchanged)"
        continue
    fi
    printf '%s\n' "${CONTENT}" > "${TARGET}"
    info "${INSTANCE}: ${NAME}"
done
